def main():
    # 加载单字码表（编码 -> [字]，与 index.py load_dict 同口径）
    single_dict = {}
    with open("wubi86_basic.txt", "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) < 2:
                continue
            code = parts[0]
            if not (len(code) >= 1 and code.isalnum()):
                continue
            single_dict.setdefault(code, []).extend(ord(ch) for ch in ''.join(parts[1:]))
    engine = PhraseEngine(single_dict)
    wb = {}
    for w in MEME_WORDS:
        code = engine.phrase_to_code(w)
        if not code:
            print(f"跳过缺字: {w}")
            continue
        wb.setdefault(code, []).append(w)
    # 同码词排一起（保持录入顺序）
    json.dump(wb, open("wubi86_meme.json", "w", encoding="utf-8"), ensure_ascii=False, indent=0)
    total = sum(len(v) for v in wb.values())
    print(f"wubi86_meme.json: {len(wb)} 码 / {total} 词")
    for code in list(wb)[:12]:
        print(f"  {code} -> {wb[code][:3]}")

if __name__ == "__main__":
    main()
