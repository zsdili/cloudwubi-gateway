def main():
    single_dict = {}
    with open("wubi86_basic.txt", "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) < 2:
                continue
            code = parts[0]
            if not (len(code) >= 1 and code.isalnum()):
                continue
            single_dict.setdefault(code, []).extend(ord(ch) for ch in ''.join(parts[1:]))
    engine = PhraseEngine(single_dict)
    wb = {}
    skip = 0
    for w in WORDS_3:
        if len(w) != 3:
            continue
        code = engine.phrase_to_code(w)
        if not code:
            skip += 1
            continue
        wb.setdefault(code, []).append(w)
    json.dump(wb, open("wubi86_3char.json", "w", encoding="utf-8"), ensure_ascii=False, indent=0)
    total = sum(len(v) for v in wb.values())
    print(f"wubi86_3char.json: {len(wb)} 码 / {total} 词（跳过缺字 {skip}）")
    for code in list(wb)[:14]:
        print(f"  {code} -> {wb[code][:2]}")

if __name__ == "__main__":
    main()
