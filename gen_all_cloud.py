for l in lines:
    if len(l) <= 4:
        continue
    code, w = l[:4], l[4:]
    if len(w) >= 3 and all('\u4e00' <= ch <= '\u9fff' for ch in w):
        mig.setdefault(code, [])
        if w not in mig[code]:
            mig[code].append(w)
json.dump(mig, open(os.path.join(BASE, "wubi86_migrated.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=0)
print(f"  迁移词库: {len(mig)} 码 / {sum(len(v) for v in mig.values())} 词（端侧三/四字全量迁移云端）")

