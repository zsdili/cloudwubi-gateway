def main():
    # 归一化（去标点、去空格）
    data = {}
    for a, b in PAIRS:
        a2 = re.sub(r'[，,。！？、\s]', '', a).strip()
        b2 = re.sub(r'[，,。！？、\s]', '', b).strip()
        if not a2 or not b2 or len(a2) < 2: continue
        data.setdefault(a2, [])
        if b2 not in data[a2]: data[a2].append(b2)
    out = os.path.join(CORPUS, "comma_pairs.json")
    with open(out, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print(f"逗号补全对: {len(data)} 组前句 → {sum(len(v) for v in data.values())} 条后句 → corpus/comma_pairs.json")
    for a in ["床前明月光", "欲穷千里目", "天生我材必有用", "路遥知马力", "上善若水", "大江东去浪淘尽"]:
        print(f"  {a} → {data.get(a, '?')}")

if __name__ == "__main__":
    main()
