def load_engine():
    single_dict = {}
    with open(os.path.join(BASE, "wubi86_basic.txt"), encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"): continue
            parts = line.split()
            if len(parts) < 2: continue
            single_dict.setdefault(parts[0], []).extend(ord(ch) for w in parts[1:] for ch in w)
    return PhraseEngine(single_dict)

def write_phrases(path, words, engine, append=False):
    mode = "a" if append else "w"
    rows = []
    existing = set()
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            for line in f:
                p = line.split()
                if len(p) >= 2: existing.add(p[1])
    new = [w for w in dict.fromkeys(words) if w not in existing]
    for w in new:
        try:
            code = engine.phrase_to_code(w)
            if code and len(code) >= 2: rows.append((code, w))
        except Exception:
            pass
    with open(path, mode, encoding="utf-8") as f:
        for code, w in rows:
            f.write(f"{code} {w}\n")
    return len(rows)

